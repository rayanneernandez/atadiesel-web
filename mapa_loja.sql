-- 1. Localização de cada produto na loja (um produto pode ter mais de uma posição)
create table if not exists public.product_locations (
  id uuid primary key default gen_random_uuid(),
  codigo text not null default '',          -- código do produto no ERP (products.sku); vazio se não houver
  nome text,                                -- nome no momento do cadastro do mapa
  movel text not null,                      -- GONDULA 1..10, PRATELEIRA 1..8, NICHO 1..8
  nivel text not null default '',           -- ex.: NÍVEL 1 - PRATELEIRA 1
  posicao text not null default '',         -- ex.: 2/3
  qtd text not null default '',             -- quantidade na prateleira (opcional)
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (codigo, movel, nivel, posicao)
);
create index if not exists product_locations_codigo_idx on public.product_locations (codigo);
alter table public.product_locations enable row level security;

-- 2. Permissão do módulo 'Mapa da Loja' (mesmo modelo dos Cupons): admin, ou permissions->'Mapa da Loja'
--    como true (acesso total) ou {view, edit, delete}
create or replace function public.map_perm(p_action text) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and (
      lower(coalesce(p.role,'')) in ('admin','administrador')
      or case
        when jsonb_typeof(p.permissions->'Mapa da Loja') = 'object'
          then coalesce((p.permissions->'Mapa da Loja'->>p_action)::boolean, p_action = 'view')
        when p.permissions->'Mapa da Loja' = 'true'::jsonb then true
        else false
      end
    )
  );
$$;

drop policy if exists product_locations_select on public.product_locations;
