drop policy if exists product_locations_update on public.product_locations;
drop policy if exists product_locations_delete on public.product_locations;
create policy product_locations_select on public.product_locations for select to authenticated using (public.map_perm('view'));
create policy product_locations_insert on public.product_locations for insert to authenticated with check (public.map_perm('edit'));
create policy product_locations_update on public.product_locations for update to authenticated using (public.map_perm('edit')) with check (public.map_perm('edit'));
create policy product_locations_delete on public.product_locations for delete to authenticated using (public.map_perm('delete'));

